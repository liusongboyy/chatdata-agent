-- =====================================================================
-- 语义域访问授权（ADR-0002 的 R1）
--
-- 背景：chat2bi_domain.perm_json.grantRoles 为空数组时，该域对**所有已通过
-- 认证的用户**开放——实测中一个无任何角色的用户能查到全量数据。
-- 应用启动时会校验这一点（DomainGrantStartupCheck），漏配则拒绝启动。
--
-- 授权原则（对应 R2）：
--   **授予域访问权 = 该域内全量可见**，除非另有 rowRules 约束。
--   因此只应把「有明确数据权限规则」的角色授予域访问权。
--
-- 本脚本刻意**不授予 `chat2bi`**：它是"能否使用问数功能"的功能性角色，
-- 不携带任何数据权限规则。若授予它，所有能问数的用户都将看到域内全量数据。
-- =====================================================================

UPDATE `chat2bi_domain`
SET `perm_json` = JSON_SET(
        `perm_json`,
        '$.grantRoles', JSON_ARRAY('区域经理', '分析师')
    ),
    `update_time` = NOW()
WHERE `id` = '6a01a7bce0174875a413f60e5bdec16b';

-- 演示的第二个域（系统用户分析域）的 colRules 引用 `区域经理` / `财务`，
-- 但演示数据中没有对应的行级规则。此处仅授予 `区域经理`，
-- 使其具备访问权；真实项目应按实际数据权限设计逐域配置。
UPDATE `chat2bi_domain`
SET `perm_json` = JSON_SET(
        `perm_json`,
        '$.grantRoles', JSON_ARRAY('区域经理')
    ),
    `update_time` = NOW()
WHERE `id` = '8422bb4067874cd5b9c8976962621104';
