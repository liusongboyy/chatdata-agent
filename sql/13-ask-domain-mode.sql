-- =====================================================================
-- 语义域增加「模式」：建模模式 / 直连模式
--
-- 依据：当前需求——「只配置数据库某些表，让模型自己读表结构写 SQL」
--
-- ⚠️ 两种模式在**权限能力上完全不同**，这是本列存在的全部理由：
--
--     MODELED（建模模式，默认）
--       走语义建模 → 产出问数 DSL → **我们自己渲染 SQL** → 行规则谓词拼进 WHERE、
--       脱敏列不进 SELECT。**行级/列级权限在这里真正生效。**
--
--     RAW（直连模式）
--       只勾几张表，把表结构 + 采样值交给模型，**模型自己写 SQL**。
--       SQL 形状任意（CTE / UNION / 子查询 / 窗口函数），我们没有安全的注入点——
--       docs/adr/0002 已评估并否决了「用 JSqlParser 解析后注入谓词」这条路。
--       因此本模式**只做表级授权**，行级/列级规则一律不生效。
--
--     所以：**RAW 域不允许配置 rowRules / colRules**。允许配置却不执行，
--     等于让管理员以为自己配了限制。这一条在三处强制：
--       ① 管理台保存时拒绝（AdminDomainService）
--       ② 启动校验报告（EngineConfigValidator）
--       ③ 问数页明示「该数据集未启用行/列权限」
--
-- 默认值必须保持 MODELED：既有域的行为不能因为加了一列而改变。
-- =====================================================================

ALTER TABLE `ask_domain`
  ADD COLUMN `mode` VARCHAR(16) NOT NULL DEFAULT 'MODELED'
  COMMENT '模式：MODELED/建模模式（含行列表权限），RAW/直连模式（只做表级授权）'
  AFTER `status` ;

-- 说明：本列没有加索引。查询按 status / id 走，模式只用于逐个域的判定，
-- 不存在「按模式筛域」的查询；真有需要时再加。
